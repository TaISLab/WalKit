import os
import subprocess
import sys

import pytest
import yaml

HERE = os.path.dirname(__file__)
ROOT = os.path.join(HERE, '..')
sys.path.insert(0, ROOT)

BOX_KEYS = ('box_frame', 'min_x', 'max_x', 'min_y', 'max_y', 'min_z', 'max_z', 'invert')


def filters(name):
    """{filterN: {name, type, params}} of a parameter file of this package, as scan_to_scan_filter_chain reads it."""
    with open(os.path.join(ROOT, 'config', name), encoding='utf-8') as f:
        params = yaml.safe_load(f)['/**']['ros__parameters']
    assert list(params) == ['filter%d' % i for i in range(1, len(params) + 1)], 'the chain reads filter1, filter2, ... in order'
    return params


@pytest.mark.parametrize('name', ['self_filter.yaml', 'nav_filter.yaml', 'feet_filter.yaml'])
def test_every_filter_is_an_official_box_filter_with_all_its_parameters(name):
    for f in filters(name).values():
        assert f['type'] == 'laser_filters/LaserScanBoxFilter'
        assert set(f['params']) == set(BOX_KEYS), 'an unknown or missing parameter is silently ignored by the filter'
        assert isinstance(f['params']['invert'], bool) and f['params']['box_frame'] == 'laser'
        p = f['params']
        assert p['min_x'] < p['max_x'] and p['min_y'] < p['max_y'] and p['min_z'] < p['max_z']


def test_the_walkers_own_structure_is_removed_not_kept():
    assert len(filters('self_filter.yaml')) >= 1
    assert all(f['params']['invert'] is False for f in filters('self_filter.yaml').values())


def test_navigation_loses_the_active_area_and_the_step_detectors_keep_only_it():
    (nav,), (feet,) = filters('nav_filter.yaml').values(), filters('feet_filter.yaml').values()
    assert nav['params']['invert'] is False and feet['params']['invert'] is True
    assert {k: v for k, v in nav['params'].items() if k != 'invert'} == {k: v for k, v in feet['params'].items() if k != 'invert'}


def test_the_generated_file_says_how_to_make_it_again():
    with open(os.path.join(ROOT, 'config', 'self_filter.yaml'), encoding='utf-8') as f:
        text = f.read()
    assert 'GENERATED by find_self_collision_boxes.py' in text and '--min-persistence' in text


@pytest.mark.parametrize('launcher,in_topic,out_topic', [
    ('self_filter.launch.py', '/scan', '/scan_filtered'),
    ('nav_filter.launch.py', '/scan_filtered', '/scan_nav'),
    ('feet_filter.launch.py', '/scan_filtered', '/scan_feet')])
def test_launchers_have_sim_time_and_debug_off_by_default_and_the_topics_of_the_chain(launcher, in_topic, out_topic):
    from launch.actions import DeclareLaunchArgument
    from launch_ros.actions import Node
    ns = {}
    with open(os.path.join(ROOT, 'launch', launcher), encoding='utf-8') as f:
        exec(compile(f.read(), launcher, 'exec'), ns)                    # noqa: S102 (the launch file, as launch loads it)
    description = ns['generate_launch_description']()
    args = {a.name: a for a in description.entities if isinstance(a, DeclareLaunchArgument)}
    assert args['sim_time'].default_value[0].text == 'false' and args['debug'].default_value[0].text == 'false'
    assert args['in_topic'].default_value[0].text == in_topic and args['out_topic'].default_value[0].text == out_topic
    assert len([e for e in description.entities if isinstance(e, Node)]) == 1
